"""
Emit CoNLL-U text for a sentence, so parser output can be frozen as a test
fixture.

Fixtures are what keep the TypeScript suite fast and hermetic: no Python, no
models, no network. They are refreshed deliberately, and a model upgrade then
shows up as a reviewable diff instead of a mystery regression.

Usage:
    python -m parser_service.to_conllu en "The boy gives the girl a book."
"""

from __future__ import annotations

import sys

from .app import PROCESSORS


def format_feats(feats: dict[str, str]) -> str:
    if not feats:
        return "_"
    return "|".join(f"{k}={feats[k]}" for k in sorted(feats))


def to_conllu(text: str, lang: str) -> str:
    import stanza

    from .app import with_terminator
    from .lemmas import check_words

    nlp = stanza.Pipeline(lang=lang, processors=PROCESSORS, download_method=None, verbose=False)
    # Same terminator fix the service applies - see `with_terminator`. Without
    # it, Russian text with no final punctuation has its last vowel split off
    # as a separate token, and fixtures generated here would bake that in.
    parsed, added_terminator = with_terminator(text)
    doc = nlp(parsed)

    out: list[str] = []
    for sent in doc.sentences:
        words = list(sent.words)
        check_words(words, lang)
        if added_terminator and words and (words[-1].upos or "") == "PUNCT":
            words.pop()
        out.append(f"# text = {sent.text[:-1] if added_terminator else sent.text}")
        out.append("# provenance = GENERATED by stanza via parser_service.to_conllu")
        out.append(f"# lang = {lang}")
        for w in words:
            feats = {}
            if w.feats and w.feats != "_":
                for item in w.feats.split("|"):
                    k, _, v = item.partition("=")
                    if k and v:
                        feats[k] = v
            out.append(
                "\t".join(
                    [
                        str(w.id),
                        w.text,
                        w.lemma or w.text,
                        w.upos or "X",
                        w.xpos or "_",
                        format_feats(feats),
                        str(w.head),
                        w.deprel or "dep",
                        "_",
                        "_",
                    ]
                )
            )
        out.append("")
    return "\n".join(out)


def main() -> None:
    if len(sys.argv) < 3:
        sys.stderr.write("usage: python -m parser_service.to_conllu <lang> <text>\n")
        raise SystemExit(2)
    lang = sys.argv[1]
    text = " ".join(sys.argv[2:])
    sys.stdout.write(to_conllu(text, lang))


if __name__ == "__main__":
    main()
