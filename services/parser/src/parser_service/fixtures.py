"""
Verify (or refresh) the engine's frozen CoNLL-U fixtures against live Stanza.

Fixtures keep the TypeScript suite hermetic, but a frozen parse is only
trustworthy if it matches what the parser actually produces. This re-parses each
fixture's own `# text` line and diffs the result.

    python -m parser_service.fixtures          # check, exit 1 on any mismatch
    python -m parser_service.fixtures --write  # overwrite with live output

The provenance comment is ignored when comparing, since it is metadata.
"""

from __future__ import annotations
from .app import with_terminator

import pathlib
import sys

import stanza

from .app import PROCESSORS
from .lemmas import check_words
from .to_conllu import format_feats

ROOT = pathlib.Path(__file__).resolve().parents[4]
FIXTURES = ROOT / "packages/engine/test/fixtures/parse"


def body(text: str) -> list[str]:
    """Token rows only - comments are metadata and must not affect the diff."""
    return [ln for ln in text.splitlines() if ln.strip() and not ln.startswith("#")]


def header(path: pathlib.Path) -> tuple[str, str]:
    text = lang = ""
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith("# text ="):
            text = line.split("=", 1)[1].strip()
        elif line.startswith("# lang ="):
            lang = line.split("=", 1)[1].strip()
    return text, lang


class _Trimmed:
    """A sentence with its synthetic terminator removed, for `render`."""

    def __init__(self, words) -> None:
        self.words = words


def render(sent, lang: str, text: str) -> str:
    check_words(sent.words, lang)
    rows = [f"# text = {text}", "# provenance = GENERATED by stanza (parser_service.fixtures)", f"# lang = {lang}"]
    for w in sent.words:
        feats: dict[str, str] = {}
        if w.feats and w.feats != "_":
            for item in w.feats.split("|"):
                k, _, v = item.partition("=")
                if k and v:
                    feats[k] = v
        rows.append(
            "\t".join(
                [
                    str(w.id), w.text, w.lemma or w.text, w.upos or "X", w.xpos or "_",
                    format_feats(feats), str(w.head), w.deprel or "dep", "_", "_",
                ]
            )
        )
    return "\n".join(rows) + "\n"


def main() -> None:
    write = "--write" in sys.argv
    paths = sorted(FIXTURES.rglob("*.conllu"))
    if not paths:
        sys.stderr.write(f"no fixtures under {FIXTURES}\n")
        raise SystemExit(2)

    pipelines: dict[str, stanza.Pipeline] = {}
    mismatched: list[str] = []

    for path in paths:
        text, lang = header(path)
        if not text or not lang:
            sys.stdout.write(f"SKIP   {path.name}: no '# text ='/'# lang =' header\n")
            continue
        if lang not in pipelines:
            pipelines[lang] = stanza.Pipeline(
                lang=lang, processors=PROCESSORS, download_method=None, verbose=False
            )
        # Same terminator fix the service and the CLI apply, so a fixture
        # generated through either path round-trips here. See
        # `parser_service.app.with_terminator`.
        parsed, added_terminator = with_terminator(text)
        doc = pipelines[lang](parsed)
        if len(doc.sentences) != 1:
            sys.stdout.write(f"SKIP   {path.name}: parsed into {len(doc.sentences)} sentences\n")
            continue

        sent = doc.sentences[0]
        if added_terminator:
            words = list(sent.words)
            if words and (words[-1].upos or "") == "PUNCT":
                words.pop()
            sent = _Trimmed(words)
        fresh = render(sent, lang, text)
        current = path.read_text(encoding="utf-8")

        if body(fresh) == body(current):
            sys.stdout.write(f"match  {path.relative_to(FIXTURES)}\n")
            continue

        mismatched.append(str(path.relative_to(FIXTURES)))
        sys.stdout.write(f"DIFFER {path.relative_to(FIXTURES)}\n")
        old, new = body(current), body(fresh)
        for i in range(max(len(old), len(new))):
            o = old[i] if i < len(old) else "(missing)"
            n = new[i] if i < len(new) else "(missing)"
            if o != n:
                sys.stdout.write(f"    committed: {o}\n    stanza:    {n}\n")
        if write:
            path.write_text(fresh, encoding="utf-8")
            sys.stdout.write(f"    -> rewritten\n")

    sys.stdout.write(
        f"\n{len(paths)} fixtures, {len(mismatched)} differ"
        + (" (rewritten)\n" if write and mismatched else "\n")
    )
    if mismatched and not write:
        sys.stdout.write("re-run with --write to accept live parser output\n")
        raise SystemExit(1)


if __name__ == "__main__":
    main()
