"""Trial: UDPipe 2 (public LINDAT service) Ukrainian models on the uk test sentences, with the same lemma repair. Sends only public Tatoeba sentences.
   services/parser/.venv/bin/python -I <this file> <out dir> <model name>
"""
import sys, json, subprocess, pathlib, time
sys.path.insert(0, 'services/parser/src')
from parser_service.app import with_terminator
from parser_service.lemmas import check_lemma
pairs = json.loads(pathlib.Path('packages/eval/data/tatoeba/pairs.json').read_text(encoding='utf-8'))['uk']
model = sys.argv[2]; out = pathlib.Path(sys.argv[1]) / ('udpipe-' + model) / 'uk'; out.mkdir(parents=True, exist_ok=True)
def call(text):
    r = subprocess.run(['curl', '-s', '-m', '60', 'https://lindat.mff.cuni.cz/services/udpipe/api/process',
                        '--data-urlencode', f'model={model}', '--data-urlencode', 'tokenizer=', '--data-urlencode', 'tagger=',
                        '--data-urlencode', 'parser=', '--data-urlencode', f'data={text}'], capture_output=True, text=True)
    return json.loads(r.stdout)['result']
bad = 0
for p in pairs:
    parsed, added = with_terminator(p['source'])
    conllu = call(parsed)
    sents, cur = [], []
    for l in conllu.split('\n'):
        if l.startswith('#'): continue
        if not l.strip():
            if cur: sents.append(cur); cur = []
            continue
        c = l.split('\t')
        if '-' in c[0] or '.' in c[0]: continue          # multiword / empty nodes
        cur.append(c)
    if cur: sents.append(cur)
    lines = []
    for i, rows in enumerate(sents):
        synthetic = added and i == len(sents) - 1
        if synthetic and rows and rows[-1][1] == '.': rows = rows[:-1]
        lines.append('# text = ' + p['source']); lines.append('# provenance = GENERATED by UDPipe 2 ' + model); lines.append('# lang = uk')
        for c in rows:
            lemma = check_lemma(c[1], c[2], c[3], c[5] if c[5] != '_' else '', 'uk')
            lines.append('\t'.join([c[0], c[1], lemma, c[3], c[4], c[5], c[6], c[7], '_', '_']))
        lines.append('')
    if not sents: bad += 1
    (out / f"{p['id']}.conllu").write_text('\n'.join(lines), encoding='utf-8')
    time.sleep(0.15)
print(model, len(pairs), 'sentences written;', bad, 'empty')
