describe('addition column', () => {
  // Verified against the live sheet: government codes are NUMERIC. There are
  // zero "(+gen)"-style codes anywhere in the dictionary.
  it('reads numeric government codes', () => {
    expect(parseAddition('(+2)').governs).toBe('Gen');
    expect(parseAddition('(+3)').governs).toBe('Dat');
    expect(parseAddition('(+4)').governs).toBe('Acc');
    expect(parseAddition('(+5)').governs).toBe('Ins');
    expect(parseAddition('(+6)').governs).toBe('Loc');
  });

  it('reads principal parts grouped by semicolon', () => {
    const info = parseAddition('(jesm, jesi, jest, jesmo, jeste, sųt; byl; bųdų)');
    expect(info.principalParts).toHaveLength(3);
    expect(info.principalParts[0]).toHaveLength(6);
    expect(info.principalParts[1]).toEqual(['byl']);
  });

  it('reads government and principal parts together', () => {
    const info = parseAddition('(podȯjde; podšėl) (+3)');
    expect(info.governs).toBe('Dat');
    expect(info.principalParts.flat()).toContain('podšėl');
  });

  it('is empty for a blank cell', () => {
    expect(parseAddition('')).toMatchObject({ principalParts: [] });
  });
});

describe('metacharacters', () => {
  it('separates flags from the text', () => {
    expect(stripMetachars('!word')).toMatchObject({ text: 'word', autogenerated: true });
    expect(stripMetachars('#word')).toMatchObject({ text: 'word', flagged: true });
    expect(stripMetachars('word')).toMatchObject({ text: 'word', autogenerated: false, flagged: false });
  });
});

describe('lemma splitting', () => {
  it('splits synonym lists', () => {
    expect(splitLemmas('altana, altanka')).toEqual(['altana', 'altanka']);
  });

  it('does not split inside parentheses', () => {
    expect(splitLemmas('byti (jesm, jesi)')).toEqual(['byti (jesm, jesi)']);
  });

  it('expands slash variants', () => {
    expect(splitLemmas('do/k')).toEqual(['do', 'k']);
  });

  it('identifies the reflexive clitic in a multiword verb', () => {
    expect(splitMultiword('bojati sę')).toMatchObject({
      head: 'bojati',
      after: 'sę',
      isMultiword: true,
      reflexive: true,
    });
  });
});

describe('xpos notation', () => {
  it('reads nouns', () => {
    expect(parseXpos('m.anim.')).toMatchObject({ upos: 'NOUN', gender: 'Masc', animate: true });
    expect(parseXpos('f.')).toMatchObject({ upos: 'NOUN', gender: 'Fem', animate: false });
    expect(parseXpos('n.pl.')).toMatchObject({ upos: 'NOUN', gender: 'Neut', numberOnly: 'Plur' });
  });

  it('reads verb aspect and transitivity', () => {
    expect(parseXpos('v.tr. ipf.')).toMatchObject({ upos: 'VERB', aspect: 'Imp', transitive: true });
    expect(parseXpos('v.tr. pf.')).toMatchObject({ aspect: 'Perf' });
    expect(parseXpos('v.intr. ipf.')).toMatchObject({ transitive: false });
  });

  /**
   * An explicit `v.intr.` and no transitivity marking at all are DIFFERENT
   * facts, and the ranker weighs them differently: an explicitly intransitive
   * verb beside a direct object is a 200-point error, an unmarked one only
   * 100, because the dictionary not saying is weaker evidence than the
   * dictionary saying no.
   *
   * Asserting only `transitive: false` cannot see the difference - an unmarked
   * verb is also not transitive. The mutation audit caught this: conflating
   * the two survived the whole suite.
   */
  it('separates an explicit intransitive marker from no marking at all', () => {
    expect(parseXpos('v.intr. ipf.')).toMatchObject({ transitive: false, intransitive: true });
    // Unmarked: the dictionary says nothing either way, so neither flag is set.
    expect(parseXpos('v. ipf.')?.intransitive).toBeFalsy();
    expect(parseXpos('v. ipf.')?.transitive).toBeFalsy();
    // And `v.tr.` is not intransitive, which the conflation would also lose.
    expect(parseXpos('v.tr. ipf.')?.intransitive).toBeFalsy();
  });

  it('gives biaspectual verbs no aspect at all', () => {
    expect(parseXpos('v.tr. ipf./pf.')?.aspect).toBeUndefined();
  });
});

describe('orthography', () => {
  it('folds etymological letters but keeps jat in the standard alphabet', () => {
    expect(toStandard('hlåpėc')).toBe('hlapec');
    expect(toStandard('knigų')).toBe('knigu');
    expect(toStandard('děvě')).toBe('děvě');
  });

  it('expands the dj digraph when folding', () => {
    expect(toStandard('međa')).toBe('medža');
  });

  it('transliterates to Cyrillic via the folded standard form', () => {
    expect(toCyrillic('hlåpėc')).toBe('хлапец');
    expect(toCyrillic('kniga')).toBe('книга');
  });

  /**
   * The orthography page calls писанје the ideal and писање only a "valid
   * alternative", allowed because "automated transliteration is unable to
   * predict whether nj should become њ or нј". The etymological spelling IS
   * that prediction, so we are not entitled to the fallback.
   * http://steen.free.fr/interslavic/orthography.html
   */
  it('keeps a softened consonant before a suffix j as two Cyrillic letters', () => {
    expect(toCyrillic('akańje')).toBe('аканје');
    expect(toCyrillic('bezusiľje')).toBe('безусилје');
    expect(toCyrillic('delfińji')).toBe('делфинји');
    expect(toCyrillic('kųpěľjų')).toBe('купєлју');
  });

  it('still writes a genuine lj/nj digraph as one Cyrillic letter', () => {
    expect(toCyrillic('pisanje')).toBe('писање');
    expect(toCyrillic('usilje')).toBe('усиље');
    expect(toCyrillic('konj')).toBe('коњ');
    expect(toCyrillic('ljudi')).toBe('људи');
  });

  it('splits nj after a Latin or Greek prefix, the page\'s other two-sound case', () => {
    expect(toCyrillic('konjunktura')).toBe('конјунктура');
    expect(toCyrillic('injekcija')).toBe('инјекција');
    // Named by the page, and missing from the reference implementation's list.
    expect(toCyrillic('panjevrějsky')).toBe('панјеврєјскы');
  });

  it('carries the two-sound rule through capitalisation', () => {
    expect(toCyrillic('Akańje')).toBe('Аканје');
    expect(toCyrillic('Konjunktura')).toBe('Конјунктура');
  });
});

describe('morphology wrapper against the real dictionary', () => {
  const ROOT = path.resolve(import.meta.dirname, '../../..');
  const lex = Lexicon.fromTsv(path.join(ROOT, 'packages/lexicon/data/raw/words.tsv'));

  it('loads the whole dictionary', () => {
    expect(lex.entries.length).toBeGreaterThan(19000);
  });

  it('selects one form by feature matching, not the whole paradigm', () => {
    const r = realize({ lemma: 'žena', xpos: 'f.', feats: { Case: 'Dat', Number: 'Sing' } });
    expect(r.ok && r.form).toBe('ženě');
  });

  it('prefers the long variant when several forms match', () => {
    const r = realize({
      lemma: 'davati',
      xpos: 'v.tr. ipf.',
      feats: { Tense: 'Pres', Person: '3', Number: 'Sing' },
    });
    // davaje (Long) and dava (Short) both match; the generator must commit.
    expect(r.ok && r.form).toBe('davaje');
  });

  /**
   * Found by differential audit against @interslavic/utils: all 155 plurale
   * tantum entries silently failed to inflect and fell back to their citation
   * form, because the library tags them Number=Ptan and selectForm matched
   * features exactly. The full-form validator could not catch it - the
   * citation form it fell back to is a real word.
   */
  it('inflects a plurale tantum noun, which has no number to choose', () => {
    const asked = (feats: Record<string, string>) =>
      realize({ lemma: 'dveri', xpos: 'f.pl.', feats });

    expect(asked({ Case: 'Gen', Number: 'Plur' })).toMatchObject({ ok: true, form: 'dverij' });
    expect(asked({ Case: 'Ins', Number: 'Plur' })).toMatchObject({ ok: true, form: 'dverami' });
    // A singular request must still resolve: the source language may say "door".
    expect(asked({ Case: 'Nom', Number: 'Sing' })).toMatchObject({ ok: true, form: 'dveri' });
  });

  it('does not let the plurale tantum relaxation loosen an ordinary noun', () => {
    // žena has real Sing/Plur forms, so a Number request must still bind.
    const r = realize({ lemma: 'žena', xpos: 'f.', feats: { Case: 'Nom', Number: 'Plur' } });
    expect(r.ok && r.form).toBe('ženy');
  });

  it('inflects the head of a multiword reflexive and keeps the clitic', () => {
    const r = realize({
      lemma: 'bojati sę',
      xpos: 'v.intr. ipf.',
      feats: { Tense: 'Pres', Person: '3', Number: 'Sing' },
    });
    expect(r.ok && r.form.endsWith(' sę')).toBe(true);
  });

  it('never throws and never returns an empty form across a broad sample', () => {
    // Totality property: the wrapper either succeeds with a non-empty string or
    // reports a reason. It must never produce undefined or "".
    const sample = lex.entries.filter((_, i) => i % 23 === 0);
    expect(sample.length).toBeGreaterThan(500);
    for (const e of sample) {
      const toks = paradigm(e.lemma, e.pos.xpos, e.addition.principalParts);
      for (const t of toks) {
        expect(typeof t.form).toBe('string');
        expect(t.form.length).toBeGreaterThan(0);
      }
    }
  });
});

describe('ranking imposes a total order', () => {
  const ROOT = path.resolve(import.meta.dirname, '../../..');
  const lex = Lexicon.fromTsv(path.join(ROOT, 'packages/lexicon/data/raw/words.tsv'));

  it('ranks deterministically regardless of input order', () => {
    const cands = lex.lookupEnglish('order');
    expect(cands.length).toBeGreaterThan(10);
    const a = rank(cands, { upos: 'NOUN', gloss: 'order' }).map((e) => e.lemma);
    const b = rank([...cands].reverse(), { upos: 'NOUN', gloss: 'order' }).map((e) => e.lemma);
    expect(a).toEqual(b);
  });

  it('respects the requested part of speech', () => {
    // "book" is both a noun (kniga) and a verb (rezervovati, "to book").
    // Without a POS criterion the ranking could return the wrong category.
    const cands = lex.lookupEnglish('book');
    expect(cands.some((e) => e.pos.upos === 'VERB')).toBe(true);
    expect(rank(cands, { upos: 'NOUN', gloss: 'book' })[0]?.lemma).toBe('kniga');
    expect(rank(cands, { upos: 'VERB', gloss: 'book' })[0]?.pos.upos).toBe('VERB');
  });

  it('breaks exact ties by lemma length then alphabetically', () => {
    // A synthetic tie, so the final tie-breakers are actually exercised: with
    // real entries the score or frequency usually separates candidates first.
    const base = {
      id: '0',
      addition: { principalParts: [], raw: '' },
      type: 1,
      frequency: 100,
      unintelligibleIn: 0,
      glosses: [{ text: 'thing', index: 0 }],
      ruGlosses: [],
      sourceGlosses: {},
      autogenerated: false,
      flagged: false,
      variantIndex: 0,
      pos: { raw: 'f.', upos: 'NOUN', xpos: 'f.', gender: 'Fem' as const },
    };
    // Length and alphabet deliberately DISAGREE here, so the length rule is
    // actually exercised rather than coinciding with alphabetical order.
    const shortButLate = { ...base, lemma: 'zz' };   // 2 chars, sorts last
    const longButEarly = { ...base, lemma: 'aaa' };  // 3 chars, sorts first

    expect(rank([longButEarly, shortButLate]).map((e) => e.lemma)).toEqual(['zz', 'aaa']);
    expect(rank([shortButLate, longButEarly]).map((e) => e.lemma)).toEqual(['zz', 'aaa']);

    // Same length -> alphabetical.
    const a = { ...base, lemma: 'bbb' };
    const b = { ...base, lemma: 'aaa' };
    expect(rank([a, b]).map((e) => e.lemma)).toEqual(['aaa', 'bbb']);
    expect(rank([b, a]).map((e) => e.lemma)).toEqual(['aaa', 'bbb']);
  });

  it('prefers a single-word lemma for a single-word source', () => {
    // A one-word source should not pick a multiword phrase when a single word
    // is available: doing so makes the phrase's own modifier collide with the
    // source's adjective ("v velikom veliky gradu").
    const base = {
      id: '0',
      addition: { principalParts: [], raw: '' },
      type: 1,
      frequency: 100,
      unintelligibleIn: 0,
      glosses: [{ text: 'thing', index: 0 }],
      ruGlosses: [],
      sourceGlosses: {},
      autogenerated: false,
      flagged: false,
      variantIndex: 0,
      pos: { raw: 'm.', upos: 'NOUN', xpos: 'm.', gender: 'Masc' as const },
    };
    // The phrase is MORE frequent, so only the preference can demote it.
    const phrase = { ...base, lemma: 'veliky grad', frequency: 9999 };
    const single = { ...base, lemma: 'grad', frequency: 100 };

    expect(rank([phrase, single], { sourceIsSingleWord: true })[0]?.lemma).toBe('grad');
    // Without the hint, frequency wins as usual.
    expect(rank([phrase, single], {})[0]?.lemma).toBe('veliky grad');
  });

  it("follows the dictionary's own variant order", () => {
    // The cell reads "kak, kako": one entry listing two accepted forms. The
    // dictionary's ordering is editorial preference, so it beats our own
    // shorter-lemma tie-break.
    const how = lex.lookupEnglish('how').filter((e) => e.pos.upos === 'ADV');
    expect(how.map((e) => e.lemma)).toEqual(expect.arrayContaining(['kak', 'kako']));
    expect(how.find((e) => e.lemma === 'kak')?.variantIndex).toBe(0);
    expect(how.find((e) => e.lemma === 'kako')?.variantIndex).toBe(1);
    expect(rank(how, { upos: 'ADV', gloss: 'how' })[0]?.lemma).toBe('kak');
  });

  it('lets aspect override raw frequency for verbs', () => {
    const give = lex.lookupEnglish('give');
    const imp = rank(give, { upos: 'VERB', gloss: 'give', aspect: 'Imp' })[0];
    const perf = rank(give, { upos: 'VERB', gloss: 'give', aspect: 'Perf' })[0];
    expect(imp?.lemma).toBe('davati');
    expect(perf?.lemma).toBe('dati');
    // dati has the higher frequency, so without the aspect filter it would win.
    expect((perf?.frequency ?? 0) > (imp?.frequency ?? 0)).toBe(true);
  });
});
