/**
 * The dictionary's `isv`, `type` and `en` cells carry leading metacharacters.
 * Verified against the live sheet (19,100 rows): `!` appears on 6 `isv` cells,
 * `#` on 79; `#` also appears on 34 `type` cells.
 */
export interface Metachars {
  text: string;
  /** `!` - the entry was generated rather than hand-authored. */
  autogenerated: boolean;
  /** `#` - the entry is flagged by the maintainers as doubtful. */
  flagged: boolean;
}

export function stripMetachars(raw: string): Metachars {
  let text = raw ?? '';
  let autogenerated = false;
  let flagged = false;
  // Metacharacters may stack, in either order.
  for (;;) {
    if (text.startsWith('!')) {
      autogenerated = true;
      text = text.slice(1);
      continue;
    }
    if (text.startsWith('#')) {
      flagged = true;
      text = text.slice(1);
      continue;
    }
    break;
  }
  return { text: text.trim(), autogenerated, flagged };
}
