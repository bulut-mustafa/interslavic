export interface Entry {
  id: string;
  lemma: string;
  pos: PosInfo;
  addition: AdditionInfo;
  /** Flavor rank 1-9. Too coarse to rank with alone: 14,163/19,100 are rank 1. */
  type: number;
  /** Corpus frequency, 0-11,399. The real tie-breaker. */
  frequency: number;
  /**
   * How many Slavic languages the dictionary marks this word as NOT
   * intelligible in: its `intelligibility` column ("be+ bg~ cs- ..."),
   * counting '-'.
   */
  unintelligibleIn: number;
  /** English glosses, in dictionary order; index 0 is the primary sense. */
  glosses: Gloss[];
  /**
   * Russian glosses, parsed with the SAME splitter as the English column. It
   * used to be a bare `split(',')`, which cut 35 rows inside a parenthesis and
   * produced keys like "лекарь (разг." that nothing can match. 9 entries were
   * left with no usable Russian key at all - including `oni`, whose cell is
   * "они (муж. род, смешанный род)", so Russian "они" ("they") could not be
   * looked up at all while every other personal pronoun could.
   */
  ruGlosses: Gloss[];
  autogenerated: boolean;
  flagged: boolean;
  /**
   * Position of this lemma within its dictionary cell. The dictionary lists
   * variants in order of preference ("kak, kako"), and that editorial judgement
   * is better information than any rule of our own, so index 0 wins.
   */
  variantIndex: number;
  /**
   * Not a dictionary entry: a name the dictionary lacks, carried over from the
   * source and declined by its ending (rules/src/proper-nouns.ts).
   */
  unlisted?: true;
}

export interface Gloss {
  /** Gloss with any trailing "(sense)" removed. */
  text: string;
  /** The parenthesised sense label, when present (837 entries have one). */
  sense?: string;
  index: number;
}

/** Normalise an English gloss for index lookup. */
export function normalizeGloss(g: string): string {
  return g
    .trim()
    .toLowerCase()
    .replace(/\s*\([^)]*\)/g, '')
    .replace(/^to\s+/, '')
    .trim();
}

/**
 * Normalise a Russian gloss. The `ru` column carries stress marks on some
 * entries (e.g. "пода́ть"), which no parser's lemma will contain, so combining
 * accents are stripped via NFD before comparison.
 */
export function normalizeRussian(g: string): string {
  return g
    .normalize('NFD')
    // Strip combining diacritics (U+0300-U+036F): the `ru` column marks
    // stress on some entries, and no parser lemma ever carries it.
    .replace(/[\u0300-\u036F]/g, '')
    .replace(/\s*\([^)]*\)/g, '')
    // Note: yo (U+0451) needs no special case - NFD decomposes it to ye plus a
    // combining diaeresis, which the diacritic strip above already removes.
    // Verified: 'самолёт' and 'самолет' both normalise to the same key.
    .trim()
    .toLowerCase();
}


function parseGlosses(raw: string): Gloss[] {
  const { text } = stripMetachars(raw ?? '');
  if (!text) return [];
  const out: Gloss[] = [];
  // Split on commas that are not inside parentheses.
  let depth = 0;
  let buf = '';
  const flush = () => {
    const t = buf.trim();
    buf = '';
    if (!t) return;
    const m = t.match(/^(.*?)\s*\(([^)]*)\)\s*$/);
    out.push(
      m?.[1]
        ? { text: m[1].trim(), sense: m[2]?.trim(), index: out.length }
        : { text: t, index: out.length },
    );
  };
  for (const ch of text) {
    if (ch === '(') depth++;
    if (ch === ')') depth = Math.max(0, depth - 1);
    if (ch === ',' && depth === 0) {
      flush();
      continue;
    }
    buf += ch;
  }
  flush();
  return out;
}

export class Lexicon {
  readonly entries: Entry[] = [];
  private readonly byGloss = new Map<string, Entry[]>();
  private readonly byRussian = new Map<string, Entry[]>();
  private readonly byLemma = new Map<string, Entry[]>();

  static fromTsv(path: string): Lexicon {
    const lx = new Lexicon();
    const lines = fs.readFileSync(path, 'utf8').split('\n');
    const header = (lines[0] ?? '').split('\t');
    const col = (name: string) => header.indexOf(name);
    const [cId, cIsv, cAdd, cPos, cType, cEn, cRu, cFreq, cIntel] = [
      col('id'), col('isv'), col('addition'), col('partOfSpeech'),
      col('type'), col('en'), col('ru'), col('frequency'), col('intelligibility'),
    ] as number[];

    for (const line of lines.slice(1)) {
      if (!line.trim()) continue;
      const f = line.split('\t');
      const isvMeta = stripMetachars(f[cIsv!] ?? '');
      const pos = parseXpos(f[cPos!] ?? '');
      if (!isvMeta.text || !pos) continue;

      const typeMeta = stripMetachars(f[cType!] ?? '');
      const glosses = parseGlosses(f[cEn!] ?? '');
      const addition = parseAddition(f[cAdd!] ?? '');

      // One Entry per lemma variant, so "altana, altanka" both become findable.
      const variants = splitLemmas(isvMeta.text);
      for (const [variantIndex, lemma] of variants.entries()) {
        lx.entries.push({
          variantIndex,
          id: f[cId!] ?? '',
          lemma,
          pos,
          addition,
          /**
           * `type` is the dictionary's intelligibility tier, documented in the
           * official schema: 1 universally intelligible, 2 regionally, 3 in
           * single languages only, 4 Church-Slavonic-derived, 5 a coined
           * neologism, 9 unclear. Lower is better, and `score()` adds it
           * directly, so the default for an EMPTY cell is a real ranking
           * decision about 799 entries, and it decides 307 contested gloss
           * keys.
           *
           * It used to default to 3, which asserts something the dictionary
           * never said and lands them in a bucket holding only 469 rows
           * (2.4%), two points behind the 74% that are tier 1.
           *
           * 2 is what the dictionary's OWN separate `intelligibility` column
           * says, counting the languages each row marks '+':
           *
           *   type 1   14,168 rows   7.04 languages
           *   (empty)     799 rows   5.07     <- measured
           *   type 2    3,493 rows   4.97     <- indistinguishable
           *   type 3      469 rows   3.94
           *
           * So an untyped row behaves like a tier-2 word. This is read off the
           * data rather than chosen, which is the only reason to prefer one
           * default over another here.
           */
          type: Number(typeMeta.text) || 2,
          frequency: Number(f[cFreq!]) || 0,
          unintelligibleIn: (f[cIntel!] ?? '').split('-').length - 1,
          glosses,
          ruGlosses: parseGlosses(f[cRu!] ?? ''),
          autogenerated: isvMeta.autogenerated,
          flagged: isvMeta.flagged || typeMeta.flagged,
        });
      }
    }

    for (const e of lx.entries) {
      for (const g of e.glosses) {
        const key = normalizeGloss(g.text);
        if (!key) continue;
        let bucket = lx.byGloss.get(key);
        if (!bucket) lx.byGloss.set(key, (bucket = []));
        bucket.push(e);
      }
      for (const g of e.ruGlosses) {
        const key = normalizeRussian(g.text);
        if (!key) continue;
        let bucket = lx.byRussian.get(key);
        if (!bucket) lx.byRussian.set(key, (bucket = []));
        bucket.push(e);
      }
      let byLemma = lx.byLemma.get(e.lemma);
      if (!byLemma) lx.byLemma.set(e.lemma, (byLemma = []));
      byLemma.push(e);
    }
    return lx;
  }

  /** All entries whose English gloss matches `word`. */
  lookupEnglish(word: string): Entry[] {
    return this.byGloss.get(normalizeGloss(word)) ?? [];
  }

  /** All entries whose Russian gloss matches `word`. */
  lookupRussian(word: string): Entry[] {
    return this.byRussian.get(normalizeRussian(word)) ?? [];
  }

  lookup(word: string, lang: string): Entry[] {
    return lang === 'ru' ? this.lookupRussian(word) : this.lookupEnglish(word);
  }

  /**
   * Entries by their INTERSLAVIC lemma. Needed where a rule names the target
   * word itself rather than reaching it through a gloss - the reflexive `sebe`
   * and the possessive `svoj`, whose English side is either missing from the
   * dictionary ("myself") or unreachable from a source lemma ("my" -> svoj).
   */
  lookupLemma(lemma: string, upos?: string): Entry[] {
    const hits = this.byLemma.get(lemma) ?? [];
    return upos ? hits.filter((e) => e.pos.upos === upos) : hits;
  }
}

export interface RankContext {
  upos?: string;
  /**
   * Required aspect. This MUST be supplied for verbs before ranking:
   * "give" yields dati (Perf, freq 7606) above davati (Imp, freq 6395), and a
   * perfective present in Interslavic reads as a FUTURE. Aspect is therefore a
   * filter on candidates, not a feature resolved after word choice.
   */
  aspect?: Aspect;
  gloss?: string;
  /** Which gloss column `gloss` should be matched against. */
  lang?: string;
  /**
   * True when the source side is a single token. A single source word should
   * prefer a single-word Interslavic lemma: picking the phrase "veliky gråd"
   * for "city" makes its modifier collide with the source's own adjective.
   */
  sourceIsSingleWord?: boolean;
  /**
   * Whether the source verb has a direct object. English "leave" is two
   * different Interslavic verbs - `ostavjati` (v.tr., "leave behind, abandon")
   * and `odhoditi` (v.intr., "go away, walk away") - and the dictionary states
   * the transitivity of each. "We must leave before midnight" has no object,
   * so the transitive reading cannot be right; "He left his keys" has one, so
   * the intransitive cannot be.
   *
   * Only a STATED mismatch counts. `v.refl.` verbs and the 78 marked with no
   * transitivity at all are not penalised either way.
   */
  hasDirectObject?: boolean;
  /**
   * UD's `PronType` from the source, which the dictionary's own pronoun
   * subtypes mirror: `pron.int.` `pron.dem.` `pron.pers.` `pron.poss.`
   * `pron.rel.` `pron.indef.` `pron.refl.`. Both sides carry the information
   * and neither was consulted, so Russian "какую" (`PronType=Int,Rel`) took
   * the INDEFINITE `kaky` ("what kind of") over the interrogative `koj`
   * ("which"), which the gold pair wants.
   *
   * A comma-separated list, as UD writes it; any match counts.
   */
  pronType?: string;
  /**
   * Content words of the source sentence, lower-cased. Used to decide whether a
   * gloss's parenthesised sense label is supported by the context: the
   * dictionary glosses `prati` as "wash (clothes), launder", so "wash the
   * clothes" selects it and a bare "wash" should not.
   */
  contextWords?: ReadonlySet<string>;
  /**
   * Interslavic lemmas that are the derived FEMALE EQUIVALENT of another
   * candidate in the same list, computed by `rank()`. An English noun that
   * marks no gender should select the base, not the marked member.
   */
  femaleEquivalents?: ReadonlySet<string>;
}

/** Whether any word of a gloss's sense label occurs in the source sentence. */
const senseSupported = (sense: string, ctx: RankContext): boolean =>
  [...sense.toLowerCase().matchAll(/[\p{L}]{3,}/gu)].some((m) => ctx.contextWords?.has(m[0]) ?? false);

/**
 * An abbreviated DOMAIN label - "(pol.)", "(med.)", "(mil.)" - rather than a
 * sense hint like "(clothes)". It says the gloss holds only inside that field,
 * so with nothing in the sentence pointing there it must not outrank a plain
 * gloss on position alone: `pravica` "right (pol.), right wing" came first for
 * "rights" over `pravo` "law, right", giving "v dostojenstvu i pravicah" where
 * van Steenbergen's UDHR has "pravah".
 *
 * A point on the score, unlike the frequency discount below, because the
 * position term decides first. Narrow on purpose: a flat penalty for EVERY
 * label was measured and rejected (verification log), and the domain labels
 * are a few dozen glosses.
 */
const isDomainLabel = (sense: string | undefined): sense is string =>
  sense !== undefined && /^[a-z]{2,6}\.$/.test(sense.trim());
const DOMAIN_LABEL_UNSUPPORTED = 2;

/** Discount applied to frequency, not a flat penalty - see `effectiveFrequency`. */
const UNSUPPORTED_SENSE_LABEL = 0.75;
const FEMALE_EQUIVALENT = 0.5;

/**
 * Frequency, weakened where the dictionary itself says this entry is a narrower
 * match than a competitor.
 *
 * It has to be expressed as a discount on frequency rather than as a point
 * penalty in `score()`, because frequency is only consulted when scores tie -
 * so a single penalty point would override a 10,000-point frequency gap. A flat
 * penalty was measured and rejected for exactly that reason: it flipped 119
 * gloss keys, many of them wrongly. See docs/verification-log.md.
 */
function effectiveFrequency(e: Entry, ctx: RankContext): number {
  let f = e.frequency;

  // A sense label narrows a gloss. If nothing in the source supports the
  // label, an unlabelled competitor is the better match for a bare source word.
  if (ctx.gloss && ctx.lang !== 'ru') {
    const key = normalizeGloss(ctx.gloss);
    const matched = e.glosses.find((g) => normalizeGloss(g.text) === key);
    if (matched?.sense && !senseSupported(matched.sense, ctx)) f *= UNSUPPORTED_SENSE_LABEL;
  }

  if (ctx.femaleEquivalents?.has(e.lemma)) f *= FEMALE_EQUIVALENT;
  return f;
}

/**
 * Deterministic candidate ordering. The final two criteria (shorter lemma, then
 * lexicographic) guarantee a total order, so output is reproducible.
 * Returns negative when `a` should be preferred.
 */
/**
 * A gloss whose capital the source contradicts. Matching ignores case, so the
 * planet `Zemja` ("Земля") and the soil `zemja` ("земля") both matched "земля"
 * equally and the planet won on a tie: "na Zemji" for "на земле". The source
 * lemma keeps the distinction - the parser capitalises a proper noun's lemma
 * and lowercases a common one - so it decides. Less than a later gloss position
 * (up to 50): a capital is a hint about the sense, not a different word.
 */
const CASE_CONTRADICTED = 10;
const capitalised = (text: string): boolean => /^\p{Lu}/u.test(text);

export function compareEntries(a: Entry, b: Entry, ctx: RankContext = {}): number {
  const score = (e: Entry) => {
    let s = 0;
    if (ctx.upos && e.pos.upos !== ctx.upos) s += 1000;
    if (ctx.aspect && e.pos.aspect && e.pos.aspect !== ctx.aspect) s += 500;
    /**
     * Transitivity contradicted by the syntax. Weighted above any
     * gloss-position difference (at most 50) and below aspect, which changes
     * the tense reading.
     *
     * A government code exempts the verb: the dictionary's `v.intr.` means
     * "takes no ACCUSATIVE object", not "takes no object at all". `izběgati
     * (+2)` "avoid" is marked intransitive and still governs a genitive
     * complement, so penalising it for having one turned "Ja izběgaju pytanja"
     * into the reflexive "Ja straniti se ... pytanje".
     */
    const governsACase = e.addition.governs !== undefined;
    /**
     * A pronoun whose subtype the source contradicts. Weighted like a stated
     * transitivity mismatch: it is explicit information on both sides, not a
     * guess. Only applied when the entry HAS a subtype, so an unmarked entry
     * is never penalised.
     */
    if (ctx.pronType && e.pos.pronType) {
      const wanted = ctx.pronType.toLowerCase().split(',').map((x) => x.trim());
      if (!wanted.includes(e.pos.pronType)) s += 200;
    }
    if (ctx.hasDirectObject === true && e.pos.intransitive && !governsACase) s += 200;
    /**
     * With an object present, prefer a verb the dictionary marks TRANSITIVE
     * over one marked neither way. Half the weight of a stated mismatch,
     * because "unmarked" is weaker evidence than "intransitive".
     *
     * This is what separates the two Russian "есть". The dictionary lists
     * inflected forms of `byti` as entries of their own - `je`, `jest`, `sųt`,
     * all glossed "есть" and all far more frequent than the verb `jesti` "to
     * eat" - the same trap as the oblique pronoun forms. They carry no
     * transitivity marker, so penalising only stated intransitives left them
     * winning: "Я никогда не ем шоколад" came out as "Ja nikogda ne JESM
     * čokoladu", which says "I am chocolate".
     *
     * Measured: 0 changes across 126 English fixtures and English gold,
     * Russian gold 8/14 -> 10/14.
     */
    if (
      ctx.hasDirectObject === true &&
      e.pos.upos === 'VERB' &&
      !e.pos.transitive &&
      !e.pos.intransitive
    ) {
      s += 100;
    }
    /**
     * English only. It exists for English polysemy - "leave" is `ostavjati`
     * (abandon) or `odhoditi` (go away), and only the missing object tells
     * them apart. A Russian verb mostly carries that difference in the word
     * itself (оставить / уйти), and where it does not, the match is a
     * homograph: "она пишет" matched the transitive `pisati` "write" and
     * `pišati` "pee" through the same unstressed gloss "писать", and this
     * penalty handed it to "pee" - "ona pišaje". Writing, reading and eating
     * are routinely used without an object.
     */
    if (ctx.hasDirectObject === false && e.pos.transitive && ctx.lang !== 'ru') s += 200;
    if (ctx.gloss) {
      if (ctx.lang === 'ru') {
        const key = normalizeRussian(ctx.gloss);
        const idx = e.ruGlosses.findIndex((g) => normalizeRussian(g.text) === key);
        s += idx < 0 ? 50 : idx;
        if (idx >= 0 && capitalised(e.ruGlosses[idx]!.text) !== capitalised(ctx.gloss)) s += CASE_CONTRADICTED;
      } else {
        const key = normalizeGloss(ctx.gloss);
        const exact = e.glosses.find((g) => normalizeGloss(g.text) === key);
        if (!exact) s += 50;
        else s += exact.index; // earlier sense wins
        if (exact && isDomainLabel(exact.sense) && !senseSupported(exact.sense, ctx)) s += DOMAIN_LABEL_UNSUPPORTED;
        if (exact && capitalised(exact.text) !== capitalised(ctx.gloss)) s += CASE_CONTRADICTED;
      }
    }
    s += e.type; // flavor rank, coarse but still a signal
    if (e.flagged) s += 5;
    if (e.autogenerated) s += 3;
    /**
     * Prefer a one-word target for a one-word source, but only as a
     * preference: for some concepts the dictionary offers nothing else.
     *
     * A trailing reflexive CLITIC is not a second word. `podobati sę` is one
     * verb, and the penalty pushed it below `prijati` for Russian "нравиться",
     * which then took an inserted clitic it did not want: "Mně prijaje se ta
     * kniga" instead of "Mně se podobaje ta kniga".
     */
    if (
      ctx.sourceIsSingleWord &&
      /\s/.test(e.lemma) &&
      !splitMultiword(e.lemma, e.pos.upos).reflexive
    ) {
      s += 20;
    }
    // Follow the dictionary's own ordering of variants before falling back to
    // any tie-break of our own.
    s += Math.min(e.variantIndex, 4);
    /**
     * A word the dictionary marks as not understood in 4 or more Slavic
     * languages loses to an equal rival. Interslavic exists to be understood
     * without study, and this is the dictionary's own per-language judgement
     * of exactly that. Without it frequency alone decided, so "car" was
     * `voz` (cs, pl only) over `avto` (10 languages).
     *
     * Measured on the gold set and every fixture: 4 takes gold 26 -> 28 and
     * changes 10 outputs; 3 gains nothing more and changes 12. Applied as a
     * score step rather than a tie-break: as the FIRST tie-break, ahead of
     * frequency, it took gold down to 23 ("idti" -> "hoditi").
     */
    if (e.unintelligibleIn >= 4) s += 1;
    return s;
  };
  const d = score(a) - score(b);
  if (d !== 0) return d;
  const fa = effectiveFrequency(a, ctx);
  const fb = effectiveFrequency(b, ctx);
  if (fa !== fb) return fb - fa;
  if (a.lemma.length !== b.lemma.length) return a.lemma.length - b.lemma.length;
  return a.lemma.localeCompare(b.lemma);
}

export function rank(entries: Entry[], ctx: RankContext = {}): Entry[] {
  // Which candidates are the derived female equivalent of another candidate can
  // only be decided with the whole list in hand, so it is computed here rather
  // than in the pairwise comparator.
  const bases = entries
    .filter((e) => e.pos.upos === 'NOUN' && e.pos.gender === 'Masc' && e.pos.animate)
    .map((e) => e.lemma);
  const femaleEquivalents = new Set<string>();
  if (bases.length > 0) {
    for (const e of entries) {
      if (e.pos.gender !== 'Fem') continue;
      if (bases.some((base) => isFemaleEquivalent(e.lemma, base))) femaleEquivalents.add(e.lemma);
    }
  }

  const withDerivation: RankContext =
    femaleEquivalents.size > 0 ? { ...ctx, femaleEquivalents } : ctx;
  return [...entries].sort((a, b) => compareEntries(a, b, withDerivation));
}
