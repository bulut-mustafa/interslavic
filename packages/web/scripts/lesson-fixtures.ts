/**
 * Freeze the parse of every lesson example that has a "Try it" link, so the
 * test that holds the translator to the lesson's sentence needs no parser.
 *
 *   npm run parser                                   (in another terminal)
 *   node --experimental-strip-types packages/web/scripts/lesson-fixtures.ts
 *
 * Writes only the fixtures that are missing; stop the parser afterwards.
 */
import fs from 'node:fs';
import path from 'node:path';
import { LESSONS } from '../src/learn/lessons.ts';
import { tryItFixture, tryItExamples } from '../src/learn/try-it.ts';

const ROOT = path.resolve(import.meta.dirname, '../../..');
const PARSER = 'http://127.0.0.1:8765/parse';

interface WireToken {
  id: number;
  form: string;
  lemma: string;
  upos: string;
  feats: Record<string, string>;
  head: number;
  deprel: string;
}

for (const { en } of tryItExamples(LESSONS)) {
  const file = path.join(ROOT, tryItFixture(en));
  if (fs.existsSync(file)) continue;
  const res = await fetch(PARSER, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({ text: en, lang: 'en' }),
  });
  const { sentences } = (await res.json()) as { sentences: { tokens: WireToken[] }[] };
  if (sentences.length !== 1) throw new Error(`"${en}" parsed as ${sentences.length} sentences`);
  const rows = [`# text = ${en}`, '# provenance = GENERATED by stanza via the parser service', '# lang = en'];
  for (const t of sentences[0]!.tokens) {
    const feats = Object.keys(t.feats).sort().map((k) => `${k}=${t.feats[k]}`).join('|') || '_';
    rows.push([t.id, t.form, t.lemma, t.upos, '_', feats, t.head, t.deprel, '_', '_'].join('\t'));
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, rows.join('\n') + '\n');
  process.stdout.write(`wrote ${path.relative(ROOT, file)}\n`);
}
